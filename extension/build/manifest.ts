/** Generated by scripts/icons.ts, copied to the output by scripts/build.ts. */
export const ICONS = { 16: 'icons/icon-16.png', 32: 'icons/icon-32.png', 48: 'icons/icon-48.png', 128: 'icons/icon-128.png' };

export interface ManifestOptions {
  appEnv: AppEnv;
  version: string;
  /** OAuth client ID ("Chrome extension" type) for chrome.identity (prod). */
  oauthClientId?: string | undefined;
}

export function buildManifest(opts: ManifestOptions): chrome.runtime.ManifestV3 {
  const dev = opts.appEnv === 'dev';
  const manifest: chrome.runtime.ManifestV3 = {
    manifest_version: 3,
    name: dev ? 'Registro de jornada (DEV)' : 'Registro de jornada',
    short_name: 'Jornada',
    description: 'Registra tu jornada y tu nivel de actividad mientras la jornada está iniciada.',
    version: opts.version,
    // 30-second chrome.alarms periods need Chrome 120+.
    minimum_chrome_version: '120',
    background: { service_worker: BACKGROUND_FILE, type: 'module' },
    icons: ICONS,
    action: { default_popup: POPUP_FILE, default_title: 'Registro de jornada', default_icon: ICONS },
    // unlimitedStorage: the offline screenshot queue (up to 20 JPEGs) exceeds the 10 MB default.
    permissions: ['storage', 'unlimitedStorage', 'alarms', 'idle', 'tabs', 'identity', 'scripting'],
    host_permissions: ['<all_urls>'],
    incognito: 'not_allowed',
    content_scripts: [
      {
        matches: ['<all_urls>'],
        js: [CONTENT_FILE],
        all_frames: false,
        run_at: 'document_start',
      },
    ],
  };
  if (dev) manifest.key = DEV_PUBLIC_KEY;
  if (!dev && opts.oauthClientId) {
    manifest.oauth2 = {
      client_id: opts.oauthClientId,
      scopes: ['openid', 'email', 'profile'],
    };
  }
  return manifest;
}
